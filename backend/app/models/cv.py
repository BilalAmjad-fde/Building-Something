import hashlib
from datetime import datetime
from uuid import UUID

from pydantic import BaseModel, Field, model_validator

EMBEDDING_DIMENSIONS = 1024  # voyage-3.5, same model used for jobs


class CVProject(BaseModel):
    name: str
    summary: str


class CVInfo(BaseModel):
    """Fields the LLM extracts from raw CV text (used for structured output)."""

    skills: list[str] = Field(default_factory=list)
    experience_years: float | None = None
    job_titles: list[str] = Field(default_factory=list)
    education: list[str] = Field(default_factory=list)
    projects: list[CVProject] = Field(default_factory=list)
    certifications: list[str] = Field(default_factory=list)
    location: str | None = None


class CV(CVInfo):
    """CV data stored in the public.cvs database table."""

    # Primary key generated by PostgreSQL when a CV is inserted.
    id: UUID | None = None

    # Optional authenticated Supabase user that owns the CV.
    user_id: UUID | None = None

    # Original uploaded PDF name and optional Supabase Storage path.
    file_name: str = Field(..., min_length=1)
    file_path: str | None = None

    # Complete text extracted from the PDF; this is required by the schema.
    raw_text: str = Field(..., min_length=1)

    # Stable hash used to prevent storing the same CV more than once.
    content_hash: str | None = None

    # Voyage embedding that matches the jobs embedding model.
    embedding: list[float] | None = Field(
        default=None,
        min_length=EMBEDDING_DIMENSIONS,
        max_length=EMBEDDING_DIMENSIONS,
    )

    # Timestamp assigned by PostgreSQL when the CV row is created.
    created_at: datetime | None = None

    def compute_hash(self) -> str:
        # Normalize whitespace so small PDF extraction differences do not change the hash.
        normalized = " ".join(self.raw_text.split())
        return hashlib.sha256(normalized.encode("utf-8")).hexdigest()

    @model_validator(mode="after")
    def set_content_hash(self) -> "CV":
        # Populate the unique content_hash automatically unless one was provided.
        if not self.content_hash:
            self.content_hash = self.compute_hash()
        return self

    def to_db_row(self) -> dict:
        # id and created_at are generated by PostgreSQL, so they must not be sent as null.
        return self.model_dump(mode="json", exclude={"id", "created_at"})